-- 주간권 설명을 실제 이용 규칙에 맞춘다.
--
-- 주간권은 시작일부터 일요일(휴무)을 뺀 6일을 이용한다. 환불 정산도 이 6일을
-- 기준으로 하는데, DB 설명은 0020 이후 '월-금 08:00-다음 날 01:00'으로 남아
-- 있어서 실제로 쓸 수 있는 날(토요일 포함, 일요일 제외)과 어긋났다.
-- 손님이 보는 문구와 정산 기준이 달라지면 환불 분쟁의 빌미가 된다.
--
-- (다른 공휴일은 휴업하지 않으므로 이용일에서 빼지 않는다.)

update public.passes
set description = '6일 이용(일요일 휴무) / 08:00-다음 날 01:00 / 커피 1일 3잔'
where name = '주간권';
